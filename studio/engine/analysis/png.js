export class Image {
  constructor(w, h, bg = [16, 16, 20]) {
    this.w = w; this.h = h; this.px = new Uint8Array(w * h * 3);
    for (let i = 0; i < w * h; i++) { this.px[i * 3] = bg[0]; this.px[i * 3 + 1] = bg[1]; this.px[i * 3 + 2] = bg[2]; }
  }
  set(x, y, c, a = 1) {
    x |= 0; y |= 0;
    if (x < 0 || y < 0 || x >= this.w || y >= this.h) return;
    const i = (y * this.w + x) * 3, p = this.px;
    if (a >= 1) { p[i] = c[0]; p[i + 1] = c[1]; p[i + 2] = c[2]; }
    else { p[i] += (c[0] - p[i]) * a; p[i + 1] += (c[1] - p[i + 1]) * a; p[i + 2] += (c[2] - p[i + 2]) * a; }
  }
  rect(x, y, w, h, c, a = 1) { for (let j = Math.max(0, y | 0); j < Math.min(this.h, (y + h) | 0); j++) for (let i = Math.max(0, x | 0); i < Math.min(this.w, (x + w) | 0); i++) this.set(i, j, c, a); }
  vline(x, y0, y1, c, a = 1, dash = 0) { for (let y = y0; y <= y1; y++) if (!dash || ((y / dash) | 0) % 2 === 0) this.set(x, y, c, a); }
  hline(x0, x1, y, c, a = 1, dash = 0) { for (let x = x0; x <= x1; x++) if (!dash || ((x / dash) | 0) % 2 === 0) this.set(x, y, c, a); }
  /** draw text with the 5x7 font; scale = integer pixel size. Returns width in px. */
  text(x, y, str, c = [230, 230, 230], scale = 1, bg = null) {
    const s = String(str);
    if (bg) this.rect(x - 1, y - 1, s.length * 6 * scale + 1, 9 * scale, bg, 0.75);
    let cx = x;
    for (const ch of s) {
      const g = FONT[ch] || FONT[ch.toUpperCase()] || FONT['?'];
      for (let r = 0; r < 7; r++) for (let b = 0; b < 5; b++) if (g[r] & (0x10 >> b)) this.rect(cx + b * scale, y + r * scale, scale, scale, c);
      cx += 6 * scale;
    }
    return cx - x;
  }
  encode() {
    const { w, h, px } = this, raw = Buffer.alloc((w * 3 + 1) * h);
    for (let y = 0; y < h; y++) {
      const o = y * (w * 3 + 1); raw[o] = 1; // Sub filter
      for (let x = 0; x < w * 3; x++) { const v = px[y * w * 3 + x], left = x >= 3 ? px[y * w * 3 + x - 3] : 0; raw[o + 1 + x] = (v - left) & 255; }
    }
    const chunk = (type, data) => {
      const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
      const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
      const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td) >>> 0);
      return Buffer.concat([len, td, crc]);
    };
    const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
    return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 6 })), chunk('IEND', Buffer.alloc(0))]);
  }
}

let CRC_T = null;
function crc32(buf) {
  if (zlib.crc32) return zlib.crc32(buf);
  if (!CRC_T) { CRC_T = new Uint32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; CRC_T[n] = c >>> 0; } }
  let c = 0xffffffff; for (let i = 0; i < buf.length; i++) c = CRC_T[(c ^ buf[i]) & 255] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** magma-like colour map, x in 0..1 */
const MAP = [[0, 0, 4], [28, 16, 68], [79, 18, 123], [129, 37, 129], [181, 54, 122], [229, 80, 100], [251, 135, 97], [254, 194, 135], [252, 253, 191]];
export function colormap(x) {
  x = Math.max(0, Math.min(1, x)) * (MAP.length - 1);
  const i = Math.min(MAP.length - 2, Math.floor(x)), f = x - i, a = MAP[i], b = MAP[i + 1];
  return [a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f, a[2] + (b[2] - a[2]) * f];
}
